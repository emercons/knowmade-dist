#!/usr/bin/env python3
"""Generate references/cli.md from the llm-wiki argparse tree.

The command specs under claude-plugin/commands/ name deterministic CLI
invocations. This script is the single source for what those invocations may
look like: it walks the real parser (``knowmade_control.cli``) and writes
every namespace, subcommand, flag and help string to
``claude-plugin/skills/knowmade/references/cli.md``.

The output is deterministic and independent of terminal width and of the Python
version's ``argparse`` help formatter: it is assembled from parser attributes,
never from ``format_help()``.

    scripts/generate-cli-reference.py            # rewrite the tracked reference
    scripts/generate-cli-reference.py --check    # exit 1 when it is stale
    scripts/generate-cli-reference.py --stdout   # print instead of writing

``tests/test-plugin-validate.sh`` runs ``--check`` so a CLI change without a
regenerated reference fails the lane, and it verifies that every
``llm-wiki <namespace> <subcommand>`` mentioned in ``commands/*.md`` exists here.
"""

from __future__ import annotations

import argparse
import os
import socket
import sys
from pathlib import Path

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parent.parent
SCRIPT_DIR = ROOT / "scripts"
OUTPUT = ROOT / "claude-plugin" / "skills" / "knowmade" / "references" / "cli.md"

if str(SCRIPT_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPT_DIR))

from knowmade_control import cli as control_cli  # noqa: E402

HEADER = """\
# llm-wiki CLI Reference

<!-- Generated by scripts/generate-cli-reference.py from the argparse tree. Do not edit by hand. -->

`llm-wiki` is the deterministic control-plane CLI. Command specs call it first
wherever a deterministic subcommand exists and reserve agent work for the
semantic passes the CLI cannot judge. This file lists every namespace,
subcommand and flag exactly as the parser defines them.

Locate the CLI through the installed plugin root (`bin/llm-wiki`); in a source
checkout use `scripts/llm-wiki`. Never assume a global install. Every
`llm-wiki <namespace> <subcommand>` named in a command spec must appear below.

Conventions shared by most namespaces: `--local` targets `.wiki/` in the
current directory, `--wiki <slug>` names a wiki in the hub registry, `--hub`
overrides hub resolution, `--private` / `--public` switch between a topic and
its `-PRIVATE` sibling, and a positional or `--path` wiki root bypasses
resolution. `--json` prints a machine-readable report where offered. Flags
listed under a namespace go before its subcommand (`archive --hub H list`);
`archive`, `schema`, `identity` and `specialist` accept them after it too.
"""


def clean(text: str | None) -> str:
    return " ".join((text or "").split())


def metavar(action: argparse.Action) -> str:
    if action.nargs == 0:
        return ""
    if action.choices is not None and not isinstance(action.metavar, str):
        return "{" + ",".join(str(choice) for choice in action.choices) + "}"
    if isinstance(action.metavar, str):
        return action.metavar
    if action.option_strings:
        return action.dest.upper()
    return action.dest


def expanded_help(parser: argparse.ArgumentParser, action: argparse.Action) -> str:
    text = action.help
    if not text or text is argparse.SUPPRESS:
        return ""
    params = dict(vars(action), prog=parser.prog)
    for key in list(params):
        if params[key] is argparse.SUPPRESS:
            del params[key]
    if params.get("choices") is not None:
        params["choices"] = ", ".join(str(choice) for choice in params["choices"])
    try:
        return clean(text % params)
    except (KeyError, TypeError, ValueError):
        return clean(text)


def exclusive_peers(parser: argparse.ArgumentParser) -> dict[int, list[argparse.Action]]:
    peers: dict[int, list[argparse.Action]] = {}
    for group in parser._mutually_exclusive_groups:  # noqa: SLF001
        members = [a for a in group._group_actions if a.help is not argparse.SUPPRESS]  # noqa: SLF001
        for action in members:
            peers[id(action)] = [other for other in members if other is not action]
    return peers


def argument_rows(parser: argparse.ArgumentParser) -> list[tuple[str, str]]:
    peers = exclusive_peers(parser)
    rows: list[tuple[str, str]] = []
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):  # noqa: SLF001
            continue
        if action.help is argparse.SUPPRESS:
            continue
        value = metavar(action)
        if action.option_strings:
            name = ", ".join(action.option_strings)
            if value:
                name += f" {value}"
            optional_marker = action.required
        else:
            name = value
            if action.nargs in ("?", "*"):
                name = f"[{name}]"
            optional_marker = action.nargs not in ("?", "*")
        notes: list[str] = []
        if action.option_strings and optional_marker:
            notes.append("required")
        default = action.default
        if default == [] or default == ():
            default = None
        if default is not None and (str(os.getpid()) in str(default) or socket.gethostname() in str(default)):
            # A per-process default (for example a host:pid worker id) would
            # make the reference differ on every machine.
            notes.append("default: generated per process")
            default = None
        if (
            default is not None
            and default is not argparse.SUPPRESS
            and default is not False
            and action.nargs != 0
            and "default" not in (action.help or "").lower()
        ):
            notes.append(f"default: {default}")
        if id(action) in peers and peers[id(action)]:
            names = " or ".join(other.option_strings[0] for other in peers[id(action)] if other.option_strings)
            if names:
                notes.append(f"not with {names}")
        text = expanded_help(parser, action)
        if notes:
            suffix = f"({'; '.join(notes)})"
            text = f"{text} {suffix}" if text else suffix
        text = text or "-"
        rows.append((name, text))
    return rows


def render_table(rows: list[tuple[str, str]]) -> list[str]:
    if not rows:
        return ["_No arguments._", ""]
    lines = ["| Argument | Meaning |", "|---|---|"]
    for name, text in rows:
        cell = name.replace("|", "\\|")
        lines.append(f"| `{cell}` | {text.replace('|', chr(92) + '|')} |")
    lines.append("")
    return lines


def subparser_action(parser: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            return action
    return None


def child_helps(action: argparse._SubParsersAction) -> dict[str, str]:
    return {item.dest: clean(item.help) for item in action._choices_actions}  # noqa: SLF001


def render_parser(
    parser: argparse.ArgumentParser, path: list[str], summary: str, depth: int
) -> list[str]:
    heading = "#" * depth + " `" + " ".join(path) + "`"
    lines = [heading, ""]
    description = clean(parser.description) or summary
    if description:
        lines += [description, ""]
    sub = subparser_action(parser)
    own_rows = argument_rows(parser)
    if sub is None:
        lines += render_table(own_rows)
        return lines
    if own_rows:
        lines += ["Options and arguments given before the subcommand:", ""]
        lines += render_table(own_rows)
    helps = child_helps(sub)
    lines += ["Subcommands: " + ", ".join(f"`{name}`" for name in sub.choices) + ".", ""]
    for name, child in sub.choices.items():
        lines += render_parser(child, path + [name], helps.get(name, ""), depth + 1)
    return lines


def generate() -> str:
    parser = control_cli.build_parser()
    sub = subparser_action(parser)
    assert sub is not None, "llm-wiki parser has no namespaces"
    helps = child_helps(sub)
    lines = HEADER.splitlines() + [""]
    lines += ["Namespaces: " + ", ".join(f"`{name}`" for name in sub.choices) + ".", ""]
    for name, child in sub.choices.items():
        lines += render_parser(child, ["llm-wiki", name], helps.get(name, ""), 2)
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv: list[str] | None = None) -> int:
    cli = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = cli.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Exit 1 when the tracked reference is stale.")
    mode.add_argument("--stdout", action="store_true", help="Print the reference instead of writing it.")
    cli.add_argument("--output", type=Path, default=OUTPUT, help="Reference path (default: the tracked file).")
    args = cli.parse_args(argv)

    text = generate()
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        current = args.output.read_bytes().decode("utf-8") if args.output.is_file() else ""
        if current != text:
            print(
                f"{args.output} is stale; run scripts/generate-cli-reference.py and commit the result.",
                file=sys.stderr,
            )
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(text.encode("utf-8"))
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
